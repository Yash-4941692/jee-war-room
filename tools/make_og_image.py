"""Generate public/og.png — the 1200x630 social/AI-preview card.

Deterministic (Pillow + DejaVu), so it can be regenerated byte-for-byte:
    python3 tools/make_og_image.py
"""
import os

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "public", "og.png")

W, H = 1200, 630
BG = (10, 13, 19)          # #0a0d13 — the app's theme-color
CARD = (18, 22, 29)        # #12161d
ACCENT = (255, 122, 26)    # #ff7a1a
TXT = (232, 237, 245)      # #e8edf5
MUTED = (147, 161, 181)    # #93a1b5
CYAN = (34, 211, 238)      # #22d3ee

FONT_DIR = "/usr/share/fonts/truetype/dejavu"
BOLD_TTF = os.path.join(FONT_DIR, "DejaVuSans-Bold.ttf")
REG_TTF = os.path.join(FONT_DIR, "DejaVuSans.ttf")


def main():
    img = Image.new("RGB", (W, H), BG)
    d = ImageDraw.Draw(img)

    # soft glow band across the top
    glow = Image.new("RGB", (W, 320), BG)
    gd = ImageDraw.Draw(glow)
    for i in range(320):
        a = max(0.0, 1 - i / 320)
        gd.line([(0, i), (W, i)],
                fill=(int(10 + 30 * a), int(13 + 18 * a), int(19 + 10 * a)))
    img.paste(glow, (0, 0))

    bold = ImageFont.truetype(BOLD_TTF, 74)
    sub = ImageFont.truetype(REG_TTF, 30)
    mid = ImageFont.truetype(BOLD_TTF, 27)
    small = ImageFont.truetype(REG_TTF, 21)

    # target mark (concentric rings) beside the wordmark
    cx, cy, R = 118, 150, 54
    for r, col, w in ((R, ACCENT, 8), (R * 0.62, TXT, 6), (R * 0.26, ACCENT, 8)):
        d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=col, width=int(w))

    d.text((200, 112), "JEE WAR ROOM", font=bold, fill=TXT)
    d.text((203, 200), "JEE Main study tracker  ·  built for two", font=sub, fill=ACCENT)

    d.text((80, 292), "Daily activity log · DPP & PYQ counts · focus timer", font=sub, fill=MUTED)
    d.text((80, 336), "Chapter-wise syllabus progress across Physics, Chemistry, Maths", font=sub, fill=MUTED)
    d.text((80, 380), "Mock analysis · mistake notebook · streak · projected AIR", font=sub, fill=MUTED)

    x = 80
    for label, col in (("61 CHAPTERS", CYAN), ("FREE · NO ADS", ACCENT), ("MOBILE-FIRST", CYAN)):
        tw = d.textlength(label, font=mid)
        d.rounded_rectangle([x, 452, x + tw + 44, 512], radius=14, fill=CARD, outline=col, width=2)
        d.text((x + 22, 468), label, font=mid, fill=col)
        x += tw + 66

    d.text((80, 552),
           "Projected AIR is a transparent estimate from your own logged work — not a rank prediction.",
           font=small, fill=MUTED)

    img.save(OUT, optimize=True)
    print("wrote %s (%dx%d)" % (OUT, W, H))


if __name__ == "__main__":
    main()
